def build(system: str, shots: list[tuple[str, str]], user: str) -> list[dict]:
    msgs = [{"role": "system", "content": system}]
    for q, a in shots:
        msgs.append({"role": "user", "content": q})
        msgs.append({"role": "assistant", "content": a})
    msgs.append({"role": "user", "content": user})
    return msgs
